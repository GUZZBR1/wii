export interface MiiValidationResult {
  readonly valid: boolean;
  readonly errors: readonly string[];
}

const HEAD_SHAPE_SET = new Set<string>(HEAD_SHAPES);
const HAIR_STYLE_SET = new Set<string>(HAIR_STYLES);
const EYEBROW_STYLE_SET = new Set<string>(EYEBROW_STYLES);
const EYE_STYLE_SET = new Set<string>(EYE_STYLES);
const NOSE_STYLE_SET = new Set<string>(NOSE_STYLES);
const MOUTH_STYLE_SET = new Set<string>(MOUTH_STYLES);
const FACIAL_HAIR_SET = new Set<string>(FACIAL_HAIR_STYLES);
const GLASSES_SET = new Set<string>(GLASSES_STYLES);
const HEX_COLOR_RE = /^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/;

function isPlainRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isUnitNumber(value: unknown): value is number {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0 && value <= 1;
}

function clampUnit(value: unknown, fallback: number): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) return fallback;
  return Math.min(1, Math.max(0, value));
}

function sanitizeHexColor(value: unknown, fallback: string): string {
  if (typeof value !== 'string') return fallback;
  const trimmed = value.trim();
  return HEX_COLOR_RE.test(trimmed) ? trimmed : fallback;
}

function sanitizeEnum<T extends string>(value: unknown, allowed: ReadonlySet<string>, fallback: T): T {
  return typeof value === 'string' && allowed.has(value) ? (value as T) : fallback;
}

export function validateMiiProfile(raw: unknown): MiiValidationResult {
  const errors: string[] = [];
  if (!isPlainRecord(raw)) {
    return { valid: false, errors: ['profile must be a plain object'] };
  }

  if (typeof raw.id !== 'string' || raw.id.trim().length === 0) {
    errors.push('id must be a non-empty string');
  }
  if (typeof raw.name !== 'string') {
    errors.push('name must be a string');
  } else {
    const trimmed = raw.name.trim();
    if (trimmed.length === 0 || trimmed.length > MII_NAME_MAX_LENGTH) {
      errors.push(`name length must be 1..${MII_NAME_MAX_LENGTH}`);
    }
  }
  if (typeof raw.isCpu !== 'boolean') errors.push('isCpu must be a boolean');
  if (!isUnitNumber(raw.skill)) errors.push('skill must be a finite number in [0, 1]');
  if (!isUnitNumber(raw.height)) errors.push('height must be a finite number in [0, 1]');
  if (!isUnitNumber(raw.build)) errors.push('build must be a finite number in [0, 1]');

  if (typeof raw.headShape !== 'string' || !HEAD_SHAPE_SET.has(raw.headShape)) errors.push('invalid headShape');
  if (typeof raw.hairStyle !== 'string' || !HAIR_STYLE_SET.has(raw.hairStyle)) errors.push('invalid hairStyle');
  if (typeof raw.eyebrowStyle !== 'string' || !EYEBROW_STYLE_SET.has(raw.eyebrowStyle)) {
    errors.push('invalid eyebrowStyle');
  }
  if (typeof raw.eyeStyle !== 'string' || !EYE_STYLE_SET.has(raw.eyeStyle)) errors.push('invalid eyeStyle');
  if (typeof raw.noseStyle !== 'string' || !NOSE_STYLE_SET.has(raw.noseStyle)) errors.push('invalid noseStyle');
  if (typeof raw.mouthStyle !== 'string' || !MOUTH_STYLE_SET.has(raw.mouthStyle)) errors.push('invalid mouthStyle');
  if (typeof raw.facialHair !== 'string' || !FACIAL_HAIR_SET.has(raw.facialHair)) errors.push('invalid facialHair');
  if (typeof raw.glasses !== 'string' || !GLASSES_SET.has(raw.glasses)) errors.push('invalid glasses');

  for (const field of ['skinTone', 'hairColor', 'eyeColor', 'shirtColor'] as const) {
    const val = raw[field];
    if (typeof val !== 'string' || !HEX_COLOR_RE.test(val.trim())) {
      errors.push(`invalid ${field}`);
    }
  }

  return { valid: errors.length === 0, errors };
}

function sanitizeFields(raw: Record<string, unknown>, base: MiiProfile): MiiProfile {
  const id = typeof raw.id === 'string' && raw.id.trim().length > 0 ? raw.id.trim() : base.id;
  const rawName = typeof raw.name === 'string' ? raw.name.trim().slice(0, MII_NAME_MAX_LENGTH) : '';
  const name = rawName.length > 0 ? rawName : base.name;
  const isCpu = typeof raw.isCpu === 'boolean' ? raw.isCpu : base.isCpu;

  return {
    id,
    name,
    isCpu,
    skill: clampUnit(raw.skill, base.skill),
    headShape: sanitizeEnum(raw.headShape, HEAD_SHAPE_SET, base.headShape),
    skinTone: sanitizeHexColor(raw.skinTone, base.skinTone),
    hairStyle: sanitizeEnum(raw.hairStyle, HAIR_STYLE_SET, base.hairStyle),
    hairColor: sanitizeHexColor(raw.hairColor, base.hairColor),
    eyebrowStyle: sanitizeEnum(raw.eyebrowStyle, EYEBROW_STYLE_SET, base.eyebrowStyle),
    eyeStyle: sanitizeEnum(raw.eyeStyle, EYE_STYLE_SET, base.eyeStyle),
    eyeColor: sanitizeHexColor(raw.eyeColor, base.eyeColor),
    noseStyle: sanitizeEnum(raw.noseStyle, NOSE_STYLE_SET, base.noseStyle),
    mouthStyle: sanitizeEnum(raw.mouthStyle, MOUTH_STYLE_SET, base.mouthStyle),
    facialHair: sanitizeEnum(raw.facialHair, FACIAL_HAIR_SET, base.facialHair),
    glasses: sanitizeEnum(raw.glasses, GLASSES_SET, base.glasses),
    height: clampUnit(raw.height, base.height),
    build: clampUnit(raw.build, base.build),
    shirtColor: sanitizeHexColor(raw.shirtColor, base.shirtColor),
  };
}

export function sanitizeMiiProfile(raw: unknown, fallback: MiiProfile = DEFAULT_PLAYER_MII): MiiProfile {
  const safeFallback =
    fallback === DEFAULT_PLAYER_MII
      ? DEFAULT_PLAYER_MII
      : sanitizeFields(fallback as unknown as Record<string, unknown>, DEFAULT_PLAYER_MII);
  if (!isPlainRecord(raw)) {
    return { ...safeFallback };
  }
  return sanitizeFields(raw, safeFallback);
}
